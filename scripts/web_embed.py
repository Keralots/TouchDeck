"""Embed the web portal (web/) into src/web_assets.h as gzipped PROGMEM arrays.

Runs before every build (extra_scripts = pre:...), or standalone:
  python scripts/web_embed.py
In web/index.html, {{v:<file>}} becomes a short hash of that file, so the
immutable-cached portal.css / portal.js URLs change whenever the file does.
"""

import gzip
import hashlib
import os
import re

ASSETS = [  # (file in web/, C name)
    ("index.html", "WEB_INDEX_HTML"),
    ("portal.css", "WEB_PORTAL_CSS"),
    ("portal-layout.css", "WEB_PORTAL_LAYOUT_CSS"),
    ("portal.js", "WEB_PORTAL_JS"),
    ("deck.js", "WEB_DECK_JS"),
]


def read(root, name):
    with open(os.path.join(root, "web", name), "rb") as f:
        return f.read().replace(b"\r\n", b"\n")  # same bytes whatever the checkout's line endings


def version(root, name):
    return hashlib.sha1(read(root, name)).hexdigest()[:8]


def build(root):
    out = [
        "// Generated by scripts/web_embed.py from web/ - do not edit.",
        "#pragma once",
        "#include <Arduino.h>",
        "",
    ]
    for name, cname in ASSETS:
        data = read(root, name)
        if name == "index.html":
            data = re.sub(rb"\{\{v:([\w.-]+)\}\}", lambda m: version(root, m.group(1).decode()).encode(), data)
        gz = gzip.compress(data, compresslevel=9, mtime=0)
        out.append("// %s: %d bytes, %d gzipped" % (name, len(data), len(gz)))
        out.append("static const uint8_t %s[] PROGMEM = {" % cname)
        for i in range(0, len(gz), 24):
            out.append("  " + ",".join("0x%02x" % b for b in gz[i : i + 24]) + ",")
        out.append("};")
        out.append("")
    return "\n".join(out)


def main(root):
    text = build(root)
    path = os.path.join(root, "src", "web_assets.h")
    try:
        with open(path, encoding="utf-8") as f:
            if f.read() == text:
                return  # unchanged: keep the timestamp, no rebuild
    except OSError:
        pass
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("web_embed: wrote src/web_assets.h")


try:
    Import("env")  # noqa: F821 - SCons
except NameError:
    env = None
main(env.subst("$PROJECT_DIR") if env else os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
